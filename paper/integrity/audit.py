"""Paper integrity audit, run before every draft goes out.
1. Provenance: every prose word is attributed with git blame. Lines last changed in a commit carrying a
   'Co-Authored-By: Claude' trailer count as AI-drafted; all other lines count as author-written.
   Rule: commit your own prose WITHOUT that trailer.
2. Overlap: 8-word sequences shared with the reference texts (baseline paper, original proposal), i.e. verbatim reuse that a
   similarity checker would flag.
Tables, figures, maths, comments and the bibliography are counted separately, not as prose.
Run from the repo root: .venv/bin/python paper/integrity/audit.py   -> paper/integrity/INTEGRITY_REPORT.md"""
import collections, glob, re, subprocess
FILES = ["paper/main.tex", "paper/e23_results.tex", "paper/conference/ConferencePaper.tex"]
REFS = sorted(glob.glob("docs/reference/*.pdf") + glob.glob("../archive_early_2026/*.pdf"))
SKIP_ENVS = ("table", "tabular", "figure", "tikzpicture", "equation", "align", "verbatim", "lstlisting", "thebibliography", "algorithm")
N = 8
W = lambda s: re.findall(r"[a-z][a-z'\-]+|\d+(?:\.\d+)?", s.lower())


def ai_commits():
    out = subprocess.run(["git", "log", "--all", "--format=%H%x00%B%x01"], capture_output=True, text=True).stdout
    return {c.split("\x00")[0].strip() for c in out.split("\x01") if "Co-Authored-By: Claude" in c}


def blame(f):
    out = subprocess.run(["git", "blame", "--line-porcelain", f], capture_output=True, text=True).stdout.splitlines()
    rows, sha = [], None
    for l in out:
        if re.match(r"^[0-9a-f]{40} ", l): sha = l[:40]
        elif l.startswith("\t"): rows.append((sha, l[1:]))
    return rows


def strip_tex(l):
    l = re.sub(r"(?<!\\)%.*", "", l); l = re.sub(r"\$[^$]*\$", " ", l)
    l = re.sub(r"\\(cite|ref|label|eqref|url|includegraphics|input|newcommand)\*?(\[[^\]]*\])?\{[^}]*\}", " ", l)
    l = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", " ", l); return re.sub(r"[{}~\\]", " ", l)


def ref_shingles():
    sh = {}
    for p in REFS:
        t = W(subprocess.run(["pdftotext", p, "-"], capture_output=True, text=True).stdout)
        for i in range(len(t) - N + 1): sh.setdefault(" ".join(t[i:i + N]), p.split("/")[-1])
    return sh


AI, REF = ai_commits(), ref_shingles(); report = []; grand = collections.Counter()
for f in FILES:
    sec, env, stats, hits = "(preamble)", [], collections.OrderedDict(), collections.defaultdict(list)
    for sha, line in blame(f):
        m = re.match(r"\s*\\(section|subsection)\*?\{(.*)\}", line)
        if m: sec = ("" if m.group(1) == "section" else "  ") + m.group(2)
        for b in re.findall(r"\\begin\{(\w+)\*?\}", line): env.append(b)
        inside = any(e.startswith(SKIP_ENVS) for e in env)
        for b in re.findall(r"\\end\{(\w+)\*?\}", line):
            if b in env: env.remove(b)
        s = stats.setdefault(sec, collections.Counter()); words = W(strip_tex(line))
        if sec == "(preamble)" or line.lstrip().startswith("%") or not words: continue
        if inside: s["tables/figures"] += len(words); continue
        s["ai" if sha in AI else "author"] += len(words)
        for i in range(len(words) - N + 1):
            g = " ".join(words[i:i + N])
            if g in REF: hits[sec].append((REF[g], g))
    rows = []
    for sec, s in stats.items():
        if sec == "(preamble)" or not (s["ai"] + s["author"] + s["tables/figures"]): continue
        grand.update(s); tot = s["ai"] + s["author"]
        rows.append(f"| {sec.strip() if not sec.startswith('  ') else '↳ ' + sec.strip()} | {s['author']} | {s['ai']} | {100 * s['ai'] / tot if tot else 0:.0f}% | {s['tables/figures']} | {len(hits[sec])} | {'rewrite' if s['ai'] else 'ok'} |")
    report += [f"\n## `{f}`\n", "| Section | Author words | AI-drafted words | AI share | Table/figure words | 8-word overlaps with references | Action |", "|---|---|---|---|---|---|---|"] + rows
    ov = [(sec, r, g) for sec, hs in hits.items() for r, g in hs]
    if ov:
        report.append("\nVerbatim overlaps (first 15; each is an 8-word sequence also found in the named reference):")
        report += [f"- {sec.strip()}: \"{g}\" ({r})" for sec, r, g in ov[:15]]
tot = grand["ai"] + grand["author"]
head = ["# Paper integrity report", "", "Generated by `paper/integrity/audit.py`. Rerun before every draft (Nov 8, Nov 15, final).", "",
        f"**AI-drafted share of prose: {100 * grand['ai'] / tot:.1f}%** ({grand['ai']} of {tot} prose words). Target < 5%.",
        f"Author-written prose: {grand['author']} words. Table/figure words (data, counted separately): {grand['tables/figures']}.",
        f"References checked for verbatim overlap: {', '.join(r.split('/')[-1] for r in REFS) or 'none'}.", "",
        "How provenance is decided: `git blame`. A line counts as AI-drafted if its last change came from a commit with a `Co-Authored-By: Claude` trailer. "
        "Rewrite a section in your own words and commit it yourself (no trailer); its words then move to the author column."]
open("paper/integrity/INTEGRITY_REPORT.md", "w").write("\n".join(head + report) + "\n"); print("\n".join(head[4:6]))
